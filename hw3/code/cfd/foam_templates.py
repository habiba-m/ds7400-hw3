def fv_schemes(steady):
    ddt = "steadyState" if steady else "backward"
    bnd = "bounded " if steady else ""
    return hdr("fvSchemes") + f"""
ddtSchemes      {{ default {ddt}; }}
gradSchemes
{{
    default         Gauss linear;
    grad(U)         cellLimited Gauss linear 1;
    grad(k)         cellLimited Gauss linear 1;
    grad(omega)     cellLimited Gauss linear 1;
}}
divSchemes
{{
    default         none;
    div(phi,U)      {bnd}Gauss linearUpwind grad(U);
    div(phi,k)      {bnd}Gauss limitedLinear 1;
    div(phi,omega)  {bnd}Gauss limitedLinear 1;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear limited corrected 0.33; }}
interpolationSchemes {{ default linear; }}
snGradSchemes   {{ default limited corrected 0.33; }}
wallDist        {{ method meshWave; }}
"""


def fv_solution(steady):
    common = """
    p
    {
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-7;
        relTol          0.01;
    }
    Phi
    {
        $p;
    }
    "(U|k|omega)"
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0.1;
    }"""
    if steady:
        return hdr("fvSolution") + f"""
solvers
{{{common}
}}

SIMPLE
{{
    nNonOrthogonalCorrectors 0;
    consistent      yes;
    residualControl {{ p 1e-5; U 1e-6; "(k|omega)" 1e-6; }}
}}

potentialFlow {{ nNonOrthogonalCorrectors 5; }}

relaxationFactors {{ equations {{ U 0.9; ".*" 0.7; }} }}
"""
    return hdr("fvSolution") + f"""
solvers
{{{common}
    pFinal
    {{
        $p;
        relTol          0;
    }}
    "(U|k|omega)Final"
    {{
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0;
    }}
}}

PIMPLE
{{
    nOuterCorrectors 2;
    nCorrectors      2;
    nNonOrthogonalCorrectors 1;
    momentumPredictor yes;
}}

potentialFlow {{ nNonOrthogonalCorrectors 5; }}

relaxationFactors {{ equations {{ ".*" 1; }} }}
"""


