def sample_dict(field, probe_points_path):
    """Probe sampling at the shared coordinates (run via postProcess -func)."""
    return hdr(f"sample{field}") + f"""
type                sets;
libs                (sampling);
interpolationScheme cellPoint;
setFormat           raw;
fields              ({field});
sets
{{
    probes
    {{
        type    cloud;
        axis    xyz;
        #include "{probe_points_path}"
    }}
}}
"""


def write_probe_points(path, pts):
    with open(path, "w") as fh:
        fh.write("points\n(\n")
        np.savetxt(fh, pts, fmt="(%.9f %.9f %.9f)")
        fh.write(");\n")
