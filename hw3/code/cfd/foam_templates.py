def k_omega_inlet(speed=cfg.U_REF):
    k = 1.5 * (cfg.TURB_INTENSITY * speed) ** 2
    omega = k / (cfg.VISC_RATIO * cfg.NU)
    return k, omega


def constant_files():
    nu = f"{cfg.NU:.10g}"
    m = cfg.TURBULENCE_MODEL
    return {
        # ESI names
        "transportProperties": hdr("transportProperties") + f"\ntransportModel Newtonian;\nnu {nu};\n",
        "turbulenceProperties": hdr("turbulenceProperties")
        + f"\nsimulationType RAS;\nRAS {{ RASModel {m}; turbulence on; printCoeffs on; }}\n",
        # Foundation (v9+) names, harmless for ESI; eases porting
        "physicalProperties": hdr("physicalProperties")
        + f"\nviscosityModel constant;\nnu [0 2 -1 0 0 0 0] {nu};\n",
        "momentumTransport": hdr("momentumTransport")
        + f"\nsimulationType RAS;\nRAS {{ model {m}; turbulence on; printCoeffs on; }}\n",
    }


def _table(times, values):
    rows = "\n".join(
        f"            ({t:.6f} {vec(v) if np.ndim(v) else f'{v:.10g}'})" for t, v in zip(times, values))
    return f"table\n        (\n{rows}\n        )"


def zero_fields(steady_u=None, table=None):
    """steady_u: constant (3,) inflow; table: (times, (T,3) velocities)."""
    k0, w0 = k_omega_inlet()
    if table is None:
        u0 = steady_u
        inlet = f"type fixedValue; value uniform {vec(u0)};"
        far = f"type inletOutlet; inletValue uniform {vec(u0)}; value uniform {vec(u0)};"
    else:
        t, U = table
        u0 = U[0]
        tab = _table(t, U)
        inlet = f"type uniformFixedValue;\n        uniformValue {tab};\n        value uniform {vec(u0)};"
        far = (f"type uniformInletOutlet;\n        uniformInletValue {tab};\n"
               f"        value uniform {vec(u0)};")

    def field(name, cls, dims, internal, bcs):
        # 0.orig is copied into processor*/0 after the parallel snappyHexMesh, so
        # every field needs an entry for the inter-processor patches too.
        bcs = {**bcs, '"procBoundary.*"': "type processor; value $internalField;"}
        body = "\n".join(f"    {p}\n    {{\n        {b}\n    }}" for p, b in bcs.items())
        return hdr(name, cls) + f"\ndimensions {dims};\n\ninternalField {internal};\n\nboundaryField\n{{\n{body}\n}}\n"

    vf, sf = "volVectorField", "volScalarField"
    return {
        "U": field("U", vf, "[0 1 -1 0 0 0 0]", f"uniform {vec(u0)}", {
            "inlet": inlet, "farfield": far,
            "outlet": "type inletOutlet; inletValue uniform (0 0 0); value $internalField;",
            "ellipsoid": "type noSlip;"}),
        "p": field("p", sf, "[0 2 -2 0 0 0 0]", "uniform 0", {
            "inlet": "type zeroGradient;", "farfield": "type zeroGradient;",
            "outlet": "type fixedValue; value uniform 0;", "ellipsoid": "type zeroGradient;"}),
        "k": field("k", sf, "[0 2 -2 0 0 0 0]", f"uniform {k0:.10g}", {
            "inlet": "type fixedValue; value $internalField;",
            "farfield": "type inletOutlet; inletValue $internalField; value $internalField;",
            "outlet": "type inletOutlet; inletValue $internalField; value $internalField;",
            "ellipsoid": "type kqRWallFunction; value $internalField;"}),
        "omega": field("omega", sf, "[0 0 -1 0 0 0 0]", f"uniform {w0:.10g}", {
            "inlet": "type fixedValue; value $internalField;",
            "farfield": "type inletOutlet; inletValue $internalField; value $internalField;",
            "outlet": "type inletOutlet; inletValue $internalField; value $internalField;",
            "ellipsoid": "type omegaWallFunction; value $internalField;"}),
        "nut": field("nut", sf, "[0 2 -1 0 0 0 0]", "uniform 0", {
            "inlet": "type calculated; value uniform 0;",
            "farfield": "type calculated; value uniform 0;",
            "outlet": "type calculated; value uniform 0;",
            "ellipsoid": "type nutkWallFunction; value uniform 0;"}),
    }


