HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by cfd/generate_cases.py -- edit config.py, not this file
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


def hdr(obj, cls="dictionary"):
    return HEADER.format(cls=cls, obj=obj)


def vec(v):
    return "(" + " ".join(f"{x:.10g}" for x in v) + ")"


