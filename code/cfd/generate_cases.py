PRELUDE = """#!/bin/bash
# Generated by cfd/generate_cases.py
set -eo pipefail
cd "${0%/*}"
NP=${NP:-%NP%}
MPIRUN=${MPIRUN:-"mpirun -np $NP"}
DATASET_ROOT=${DATASET_ROOT:-%ROOT%}
CFD_TOOLS=${CFD_TOOLS:-%TOOLS%}
# The OpenFOAM module puts a Python-3.13 SciPy bundle on PYTHONPATH, which breaks other
# Pythons (e.g. miniforge 3.14). Use the first interpreter that can import numpy + scipy.
if [ -z "${PY:-}" ]; then
    for cand in "python3" "env -u PYTHONPATH python3" "python3.13"; do
        if $cand -c "import numpy, scipy" > /dev/null 2>&1; then PY="$cand"; break; fi
    done
    [ -n "${PY:-}" ] || { echo "no python with numpy+scipy found"; exit 1; }
fi
step() { echo "[$(date +%F' '%T)] $1"; }
run()  { local log=$1; shift; step "$log"; "$@" > "log.$log" 2>&1 || { echo "FAILED: $log (see log.$log)"; exit 1; }; }
"""

MESH_STEPS = """
mkdir -p constant/triSurface
cp "$DATASET_ROOT/geometry/ellipsoid.stl" "$DATASET_ROOT/geometry/near.stl" constant/triSurface/
rm -rf processor* 0
run blockMesh      blockMesh
run decomposeMesh  decomposePar -force
run snappyHexMesh  $MPIRUN snappyHexMesh -parallel -overwrite
"""

FIELDS_TO_PROCESSORS = """
for d in processor*; do rm -rf "$d/0"; cp -r 0.orig "$d/0"; done
"""

SAMPLE_AND_EXPORT = """
run writeCellCentres $MPIRUN postProcess -parallel -func writeCellCentres %CTIME%
run sampleU          $MPIRUN postProcess -parallel -func sampleU %TIMESEL%
run sampleP          $MPIRUN postProcess -parallel -func sampleP %TIMESEL%
run export           $PY "$CFD_TOOLS/export_case.py" . --kind %KIND% \\
                         --probes "$DATASET_ROOT/probes/probes.npy" \\
                         --out "$DATASET_ROOT/exports/%NAME%"
if [ "${KEEP_PROCESSOR:-0}" != "1" ]; then rm -rf processor*; fi
touch DONE
step "done"
"""


def allrun_A(name, root):
    return (PRELUDE + MESH_STEPS + """
run checkMesh      $MPIRUN checkMesh -parallel -constant
""" + FIELDS_TO_PROCESSORS + """
run potentialFoam  $MPIRUN potentialFoam -parallel -writephi
run simpleFoam     $MPIRUN simpleFoam -parallel
""" + SAMPLE_AND_EXPORT).replace("%TIMESEL%", "-latestTime").replace("%CTIME%", "-latestTime") \
        .replace("%KIND%", "A") \
        .replace("%NAME%", name)


def allrun_B_mesh():
    return PRELUDE + MESH_STEPS + """
run checkMesh      $MPIRUN checkMesh -parallel -constant
touch DONE
step "done"
"""


def allrun_B_solve(name, mesh_case, export_from):
    return (PRELUDE + f"""
[ -f "../{mesh_case}/DONE" ] || {{ echo "mesh ../{mesh_case} not built"; exit 1; }}
rm -rf processor* 0
step "copy decomposed mesh"
for d in ../{mesh_case}/processor*; do
    p=$(basename "$d"); mkdir -p "$p/constant"; cp -r "$d/constant/polyMesh" "$p/constant/"
done
""" + FIELDS_TO_PROCESSORS + """
run potentialFoam  $MPIRUN potentialFoam -parallel -writephi
run pimpleFoam     $MPIRUN pimpleFoam -parallel
""" + SAMPLE_AND_EXPORT).replace("%TIMESEL%", f"-time '{export_from:g}:'") \
        .replace("%CTIME%", f"-time {export_from:g}") \
        .replace("%KIND%", "B").replace("%NAME%", name)


def slurm(job, case_list, n, time, root, array_limit=10):
    s = cfg.SLURM
    mods = "\n".join([f"module load {m}" for m in s["modules"] + [s["python_module"]]]
                     + list(s.get("setup", [])))
    return f"""#!/bin/bash
#SBATCH -J {job}
#SBATCH -A {s['account']}
#SBATCH -p {s['partition']}
#SBATCH -N 1
#SBATCH --ntasks={s['n_procs']}
#SBATCH --mem-per-cpu={s['mem_per_cpu']}
#SBATCH -t {time}
#SBATCH --array=0-{n - 1}%{array_limit}
#SBATCH -o {root}/slurm_logs/{job}_%a.out

module purge
{mods}

export NP=$SLURM_NTASKS
export DATASET_ROOT="{root}"
export CFD_TOOLS="{TOOLS_DIR}"
CASE=$(sed -n "$((SLURM_ARRAY_TASK_ID + 1))p" "{root}/{case_list}")
[ -f "$CASE/DONE" ] && {{ echo "$CASE already done"; exit 0; }}
bash "$CASE/Allrun"
"""


