"""Generate every OpenFOAM case for Datasets A and B.

    python generate_cases.py --root /scratch/crv4jj/ellipsoid_datasets

Layout under --root:
    geometry/            ellipsoid.stl (body), near.stl (rho = 3 refinement region)
    probes/              probes.npy, probe_groups.npz, probePoints (shared by every case)
    A/A_m00 ... A_m49/   steady simpleFoam, one per mesh resolution, identical forcing
    B/mesh_m00 ... m03/  meshing-only cases (each mesh is built ONCE, kept decomposed)
    B/B_m00_<sched>/     pimpleFoam cases; copy the decomposed mesh from B/mesh_mXX, so all
                         schedules on one resolution share an identical mesh (and cell order)
    splits.json          train / val / test run names (by schedule, plus the held-out mesh)

Nothing is reconstructed: solver, sampling and export all work on processor*/ directly.
    manifest.json        every case, its parameters and output paths
    cases_*.txt, *.slurm, submit_all.sh
"""
import argparse
import json
import os
import shutil
import stat
from pathlib import Path

import numpy as np

import config as cfg
import foam_templates as ft
from geometry import ellipsoid_mesh, make_probes, write_binary_stl

TOOLS_DIR = Path(__file__).resolve().parent


def write(path, text, executable=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    if executable:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)


def estimate_cells(h):
    """Very rough cell-count estimate (order of magnitude, for planning only)."""
    r = cfg.REFINEMENT
    a, b, c = cfg.SEMI_AXES
    vol = np.prod(cfg.DOMAIN[:, 1] - cfg.DOMAIN[:, 0])
    near = 4 / 3 * np.pi * (27 - 1) * a * b * c
    (x0, y0, z0), (x1, y1, z1) = r["wake_box"]
    wake = (x1 - x0) * (y1 - y0) * (z1 - z0)
    p = 1.6075
    area = 4 * np.pi * (((a * b) ** p + (a * c) ** p + (b * c) ** p) / 3) ** (1 / p)
    hs = h / 2 ** r["surface_level"][1]
    shell = area * (r["n_cells_between_levels"] + 1) * hs / hs**3
    return int(vol / h**3 + near / (h / 2 ** r["near_level"]) ** 3
               + wake / (h / 2 ** r["wake_level"]) ** 3 + shell)


