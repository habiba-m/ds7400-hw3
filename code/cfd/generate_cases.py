def write_mesh_files(case, h):
    bm, n = ft.block_mesh_dict(h)
    write(case / "system/blockMeshDict", bm)
    write(case / "system/snappyHexMeshDict", ft.snappy_dict())
    write(case / "system/meshQualityDict", ft.MESH_QUALITY)
    write(case / "system/controlDict", ft.MESH_CONTROL)
    # snappyHexMesh reads the numerics dictionaries too; solver cases overwrite these
    write(case / "system/fvSchemes", ft.fv_schemes(True))
    write(case / "system/fvSolution", ft.fv_solution(True))
    write(case / "system/decomposeParDict", ft.decompose_dict(cfg.SLURM["n_procs"]))
    return n


def write_solver_files(case, steady, zero, probe_file):
    for name, text in ft.constant_files().items():
        write(case / "constant" / name, text)
    for name, text in zero.items():
        write(case / "0.orig" / name, text)
    write(case / "system/controlDict", ft.control_dict(steady))
    write(case / "system/fvSchemes", ft.fv_schemes(steady))
    write(case / "system/fvSolution", ft.fv_solution(steady))
    write(case / "system/sampleU", ft.sample_dict("U", probe_file))
    write(case / "system/sampleP", ft.sample_dict("p", probe_file))
    (case / "case.foam").touch()


def forcing_table(fn):
    b = cfg.DATASET_B
    t = np.arange(0.0, b["t_end"] + b["table_dt"] / 2, b["table_dt"])
    speed, yaw = fn(t - b["t_spinup"])
    speed, yaw = np.broadcast_to(speed, t.shape), np.broadcast_to(yaw, t.shape)
    U = np.stack([cfg.freestream(s, y) for s, y in zip(speed, yaw)])
    return t, speed, yaw, U


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, type=Path)
    ap.add_argument("--only", choices=["A", "B"])
    ap.add_argument("--force", action="store_true", help="overwrite existing case directories")
    args = ap.parse_args()
    root = args.root.resolve()
    root.mkdir(parents=True, exist_ok=True)
    (root / "slurm_logs").mkdir(exist_ok=True)
    (root / "exports").mkdir(exist_ok=True)

    # geometry (identical STL for every mesh)
    v, f = ellipsoid_mesh(cfg.SEMI_AXES, cfg.STL_SUBDIV)
    (root / "geometry").mkdir(exist_ok=True)
    write_binary_stl(root / "geometry/ellipsoid.stl", v, f, "ellipsoid")
    v3, f3 = ellipsoid_mesh(3 * np.array(cfg.SEMI_AXES), 4)
    write_binary_stl(root / "geometry/near.stl", v3, f3, "near")

    # shared probes
    pts, groups = make_probes()
    (root / "probes").mkdir(exist_ok=True)
    np.save(root / "probes/probes.npy", pts)
    np.savez(root / "probes/probe_groups.npz", **groups)
    probe_file = root / "probes/probePoints"
    ft.write_probe_points(probe_file, pts)

    manifest = dict(config=dict(semi_axes=cfg.SEMI_AXES, domain=cfg.DOMAIN.tolist(),
                                u_ref=cfg.U_REF, nu=cfg.NU, model=cfg.TURBULENCE_MODEL,
                                refinement=cfg.REFINEMENT),
                    probes=dict(path=str(root / "probes/probes.npy"), n=len(pts),
                                groups={k: len(g) for k, g in groups.items()}),
                    cases=[])

    def fresh(case):
        if case.exists():
            if not args.force:
                raise SystemExit(f"{case} exists; use --force to overwrite")
            shutil.rmtree(case)
        case.mkdir(parents=True)

    sub = ["#!/bin/bash", "set -e", f'cd "{root}"']
    if args.only in (None, "A"):
        A = cfg.DATASET_A
        names = []
        for i, h in enumerate(cfg.mesh_sizes(A)):
            name = f"A_m{i:02d}"
            case = root / "A" / name
            fresh(case)
            n = write_mesh_files(case, h)
            u = cfg.freestream(A["speed"], A["yaw_deg"])
            write_solver_files(case, True, ft.zero_fields(steady_u=u), probe_file)
            write(case / "Allrun", allrun_A(name, root).replace("%NP%", str(cfg.SLURM["n_procs"]))
                  .replace("%ROOT%", str(root)).replace("%TOOLS%", str(TOOLS_DIR)), True)
            np.save(case / "constant/forcing.npy",
                    np.array([[0.0, A["speed"], A["yaw_deg"], *u]]))
            names.append(str(case))
            manifest["cases"].append(dict(
                name=name, dataset="A", mesh_index=i, h=float(h), background_cells=n,
                est_cells=estimate_cells(h), steady=True, speed=A["speed"], yaw_deg=A["yaw_deg"],
                freestream=[*u.tolist(), 0.0], case_dir=str(case),
                export_dir=str(root / "exports" / name)))
        write(root / "cases_A.txt", "\n".join(names) + "\n")
        write(root / "run_A.slurm", slurm("ellA", "cases_A.txt", len(names), cfg.SLURM["time_A"], root))
        sub.append("sbatch run_A.slurm")

    if args.only in (None, "B"):
        B = cfg.DATASET_B
        schedules = cfg.make_schedules()
        splits = dict(train=[], val=[], test=[], test_flow=[], test_mesh=[])
        mesh_names, solve_names = [], []
        for i, h in enumerate(cfg.mesh_sizes(B)):
            mname = f"mesh_m{i:02d}"
            mcase = root / "B" / mname
            fresh(mcase)
            n = write_mesh_files(mcase, h)
            write(mcase / "Allrun", allrun_B_mesh().replace("%NP%", str(cfg.SLURM["n_procs"]))
                  .replace("%ROOT%", str(root)).replace("%TOOLS%", str(TOOLS_DIR)), True)
            mesh_names.append(str(mcase))
            for cond, sch in schedules.items():
                name = f"B_m{i:02d}_{cond}"
                holdout = i == B["holdout_mesh"]
                split = "test" if holdout else sch["split"]
                splits[split].append(name)
                if split == "test":
                    splits["test_mesh" if holdout else "test_flow"].append(name)
                case = root / "B" / name
                fresh(case)
                write_mesh_files(case, h)   # only decomposeParDict is used; others kept for provenance
                t, speed, yaw, U = forcing_table(sch["fn"])
                write_solver_files(case, False, ft.zero_fields(table=(t, U)), probe_file)
                np.save(case / "constant/forcing.npy", np.column_stack([t, speed, yaw, U]))
                write(case / "Allrun", allrun_B_solve(name, mname, B["export_from"])
                      .replace("%NP%", str(cfg.SLURM["n_procs"])).replace("%ROOT%", str(root))
                      .replace("%TOOLS%", str(TOOLS_DIR)), True)
                solve_names.append(str(case))
                manifest["cases"].append(dict(
                    name=name, dataset="B", mesh_index=i, h=float(h), background_cells=n,
                    est_cells=estimate_cells(h), steady=False, condition=cond, family=sch["family"],
                    schedule_params=sch["params"], split=split, holdout_mesh=holdout,
                    mesh_case=str(mcase), t_spinup=B["t_spinup"], t_end=B["t_end"],
                    write_dt=B["write_dt"], export_from=B["export_from"],
                    case_dir=str(case), export_dir=str(root / "exports" / name)))
        (root / "splits.json").write_text(json.dumps(splits, indent=1))
        write(root / "cases_B_mesh.txt", "\n".join(mesh_names) + "\n")
        write(root / "cases_B.txt", "\n".join(solve_names) + "\n")
        write(root / "run_B_mesh.slurm", slurm("ellBmesh", "cases_B_mesh.txt", len(mesh_names),
                                               "06:00:00", root))
        write(root / "run_B.slurm", slurm("ellB", "cases_B.txt", len(solve_names),
                                          cfg.SLURM["time_B"], root))
        sub += ["jid=$(sbatch --parsable run_B_mesh.slurm)",
                "sbatch --dependency=afterok:${jid} run_B.slurm"]

    write(root / "submit_all.sh", "\n".join(sub) + "\n", True)
    (root / "manifest.json").write_text(json.dumps(manifest, indent=1))

    est = [(c["name"], c["est_cells"]) for c in manifest["cases"]]
    for ds in ("A", "B"):
        e = [n for name, n in est if name.startswith(ds)]
        if e:
            print(f"Dataset {ds}: {len(e)} cases, est. cells {min(e)/1e6:.2f}M - {max(e)/1e6:.2f}M")
    print(f"probes: {len(pts)} points  {dict((k, len(g)) for k, g in groups.items())}")
    print(f"wrote {root}/manifest.json; edit SLURM in config.py, then run {root}/submit_all.sh")


if __name__ == "__main__":
    main()
